// Builds keystone-core's checks to WebAssembly and writes them into
// js/keystone-core.wasm.generated.ts, which js/keystone-core.ts loads.
// Run from anywhere: `node wasm/build.mjs`. The app and the extension run it before they
// build, test or type-check. Needs Rust (rust-toolchain.toml lists the wasm target).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

execFileSync(
  'cargo',
  ['build', '--quiet', '--target', 'wasm32-unknown-unknown', '-p', 'keystone-wasm', '--profile', 'wasm'],
  { cwd: root, stdio: 'inherit' },
);

const wasm = readFileSync(join(root, 'target/wasm32-unknown-unknown/wasm/keystone_wasm.wasm'));
const out = join(here, 'js/keystone-core.wasm.generated.ts');
const text =
  '// Generated by wasm/build.mjs from wasm/src/lib.rs. Do not edit; do not commit.\n' +
  `export const WASM_BASE64 = '${wasm.toString('base64')}';\n`;

let old = '';
try {
  old = readFileSync(out, 'utf8');
} catch {
  // first build
}
if (old !== text) writeFileSync(out, text);
